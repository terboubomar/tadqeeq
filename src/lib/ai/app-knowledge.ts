export function normalizeAppRoute(route: string | null | undefined): string {
  if (!route) return "/dashboard";
  const clean = route.split("?")[0]?.split("#")[0] || "/dashboard";
  if (clean === "/ask") return "/dashboard";
  return clean;
}
