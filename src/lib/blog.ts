export function blogPostBySlug(slug: string): BlogPost {
  const post = BLOG_POSTS.find((candidate) => candidate.slug === slug);
  if (!post) throw new Error("Unknown blog post: " + slug);
  return post;
}

/** A post as Markdown for llms-full.txt: the guide shape plus its sources. */
export function blogMarkdown(post: BlogPost, siteUrl: string): string {
  const sources = post.sources.map((source) => `- ${source.publisher}, ${source.date}: ${source.title} (${source.url})`);
  return [guideMarkdown(post, siteUrl), "", "### المصادر", "", ...sources].join("\n");
}
