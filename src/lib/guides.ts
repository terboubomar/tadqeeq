export function guideBySlug(slug: string): Guide {
  const guide = GUIDES.find((candidate) => candidate.slug === slug);
  if (!guide) throw new Error("Unknown guide: " + slug);
  return guide;
}

/** A guide as Markdown, for llms-full.txt. */
/** Markdown for llms-full.txt; also used for product pages, which share the same shape. */
export function guideMarkdown(guide: Pick<Guide, "title" | "path" | "updated" | "answer" | "sections" | "faqs">, siteUrl: string): string {
  const parts = [`## ${guide.title}`, "", `${siteUrl}${guide.path} · Updated ${guide.updated}`, "", guide.answer];
  for (const section of guide.sections) {
    parts.push("", `### ${section.heading}`);
    for (const paragraph of section.paragraphs ?? []) parts.push("", paragraph);
    if (section.steps) parts.push("", ...section.steps.map((step, index) => `${index + 1}. ${step}`));
    if (section.bullets) parts.push("", ...section.bullets.map((bullet) => `- ${bullet}`));
    if (section.table) {
      parts.push("", `| ${section.table.head.join(" | ")} |`, `| ${section.table.head.map(() => "---").join(" | ")} |`);
      parts.push(...section.table.rows.map((row) => `| ${row.join(" | ")} |`));
    }
    if (section.quote) parts.push("", ...section.quote.split("\n").map((line) => `> ${line}`));
  }
  parts.push("", "### أسئلة شائعة");
  for (const [question, answer] of guide.faqs) parts.push("", `**${question}**`, "", answer);
  return parts.join("\n");
}
